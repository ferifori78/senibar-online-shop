import client from './client'

export const adminApi = {
  dashboard: () => client.get('/admin/dashboard/'),
  board: (params) => client.get('/admin/board/', { params }),

  // Orders
  orders: (params) => client.get('/orders/', { params }),
  order: (number) => client.get(`/orders/${number}/`),
  setStatus: (number, payload) => client.post(`/orders/${number}/status/`, payload),

  // Catalog — products
  products: (params) => client.get('/products/', { params }),
  product: (slug) => client.get(`/products/${slug}/`),
  createProduct: (payload) => client.post('/products/', payload),
  updateProduct: (slug, payload) => client.patch(`/products/${slug}/`, payload),
  // Deleting erases a product nothing references, and archives one that has
  // orders or batches — the response says which happened.
  deleteProduct: (slug) => client.delete(`/products/${slug}/`),
  archiveProduct: (slug) => client.post(`/products/${slug}/archive/`),
  // Shelf order, as a list of slugs in the order they should appear.
  reorderProducts: (order) => client.post('/products/reorder/', { order }),

  // Catalog — product gallery
  productImages: (slug) => client.get(`/products/${slug}/images/`),
  uploadProductImage: (slug, file, altText = '') => {
    const body = new FormData()
    body.append('image', file)
    if (altText) body.append('alt_text', altText)
    // The boundary is generated by the browser and must appear in the header,
    // so the content type is left unset rather than inheriting the client's
    // application/json default.
    return client.post(`/products/${slug}/images/`, body, {
      headers: { 'Content-Type': undefined },
    })
  },
  deleteProductImage: (slug, id) => client.delete(`/products/${slug}/images/${id}/`),
  setProductCover: (slug, id) => client.post(`/products/${slug}/images/${id}/cover/`),
  reorderProductImages: (slug, order) =>
    client.post(`/products/${slug}/images/reorder/`, { order }),

  // Users
  users: (params) => client.get('/admin/users/', { params }),
  user: (id) => client.get(`/admin/users/${id}/`),
  userOrders: (id) => client.get(`/admin/users/${id}/orders/`),
  setUserRole: (id, role) => client.post(`/admin/users/${id}/role/`, { role }),
  setUserActive: (id, is_active) => client.post(`/admin/users/${id}/active/`, { is_active }),

  // Payment gateways — the switch only; keys live in .env on the server.
  gateways: () => client.get('/admin/gateways/'),
  setGatewayEnabled: (name, payload) =>
    client.post(`/admin/gateways/${name}/enabled/`, payload),

  // Shipping methods
  shippingMethods: () => client.get('/admin/shipping-methods/'),
  createShippingMethod: (payload) => client.post('/admin/shipping-methods/', payload),
  updateShippingMethod: (id, payload) =>
    client.patch(`/admin/shipping-methods/${id}/`, payload),
  deleteShippingMethod: (id) => client.delete(`/admin/shipping-methods/${id}/`),

  // Inventory
  inventory: () => client.get('/admin/inventory/'),
  adjustmentLog: (params) => client.get('/admin/inventory/log/', { params }),
  adjustStock: (batchId, payload) =>
    client.post(`/admin/batches/${batchId}/adjust/`, payload),

  // Catalog — roast batches
  batches: (params) => client.get('/batches/', { params }),
  createBatch: (payload) => client.post('/batches/', payload),
  updateBatch: (id, payload) => client.patch(`/batches/${id}/`, payload),
  deleteBatch: (id) => client.delete(`/batches/${id}/`),
}

export default adminApi
